/* Turns scripts/course-content.data.mjs into one idempotent SQL migration.

   Two hard safety rules, because this session has no live database access and
   the file is pasted into Supabase's SQL editor by hand:

   1. NOTHING IS EVER DELETED. modules/lessons/materials are inserted with a
      `WHERE NOT EXISTS` guard on (course_id, id), so re-running the file is a
      no-op and the five courses that already carry hand-written rows keep
      them byte-for-byte. Those five courses' m1/m2 entries in the data file
      deliberately mirror what is already stored, so the guard skips them and
      only the genuinely new modules land. A DELETE would have been simpler,
      but lesson rows are referenced by student progress — losing them to
      regenerate identical text is not a trade worth making.

   2. COURSE COLUMNS ARE ONLY FILLED WHERE EMPTY. The UPDATE uses
      COALESCE/NULLIF so a summary somebody already wrote is never overwritten
      by the generated one.

   Lesson durations are derived deterministically from the lesson id, so the
   generated file is byte-identical between runs (no random churn in git).

   Usage: node scripts/build-course-sql.mjs > course-content.sql            */

import { COURSE_CONTENT } from './course-content.data.mjs';

/* The catalogue slugs that exist in `courses`. Regenerate with:
     curl -s "$URL/rest/v1/courses?status=eq.live&select=id" -H "apikey: $ANON" */
const KNOWN_IDS = new Set([
  'masin-oyrenmesine-giris', 'power-bi-ile-biznes-analitikasi', 'python-data-analitikasi',
  'python-proqramlasdirmaya-giris', 'obyekt-yonumlu-proqramlasdirma-java', 'komputer-elmlerinin-esaslari',
  'nodejs-ve-expressjs-ile-backend-arxitekturasi', 'sebeke-esaslari-ve-it-destek',
  'kibertehlukesizliye-giris', 'bulud-texnologiyalari-aws-esaslari',
  'ictimai-sehiyyeye-giris', 'qidalanma-ve-saglam-heyat-terzi',
  'saglamliq-sistemlerinin-idare-edilmesi', 'zehni-saglamliq-ve-stress-idareetmesi',
  'muhendislik-mexanikasinin-esaslari', 'yenilene-bilen-enerji-menbeleri',
  'fizikaya-giris-klassik-mexanika', 'cad-ile-3d-modellesdirme',
  'psixologiyaya-giris', 'sosiologiya-cemiyyeti-anlamaq', 'beynelxalq-munasibetlere-giris',
  'davranis-iqtisadiyyati', 'sahibkarliq-esaslari-fikirden-mehsula', 'maliyye-analizi-ve-budcelme',
  'layihe-idareetmesi-agile-scrum', 'reqemsal-marketinq-strategiyasi',
  'turk-dilinde-serbest-danisiq', 'rus-dili-esaslari', 'ielts-e-hazirliq-proqrami',
  'ingilis-dili-biznes', 'fotoqrafiya-seneti', 'dunya-tarixine-seyahet',
  'yaradici-yazi-seneti', 'qrafik-dizayn-esaslari', 'vaxt-idareetmesi-ve-mehsuldarliq',
  'effektiv-unsiyyet-ve-natiqlik', 'liderlik-bacariqlari', 'karyera-planlamasi-ve-cv-hazirligi',
  'xetti-cebre-giris', 'ehtimal-nezeriyyesi-ve-statistika', 'mentiqi-dusunce-ve-problem-helli',
  'kalkulusun-esaslari',
]);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (items) => `ARRAY[${items.map(q).join(', ')}]::text[]`;

/* Stable pseudo-duration in the 7:00–16:59 range, seeded by the lesson id so
   two runs of this script produce the same file. */
function duration(seed) {
  let h = 0;
  for (let i = 0; i < seed.length; i += 1) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  return `${7 + (h % 10)}:${String(h % 60).padStart(2, '0')}`;
}

/* --- validation: fail loudly rather than emit SQL that inserts orphans --- */
const seen = new Set();
for (const c of COURSE_CONTENT) {
  if (!KNOWN_IDS.has(c.id)) throw new Error(`Unknown course id: ${c.id}`);
  if (seen.has(c.id)) throw new Error(`Duplicate course id: ${c.id}`);
  seen.add(c.id);
  if (!c.summary || !c.mentor || !c.mentorTitle) throw new Error(`Incomplete course: ${c.id}`);
  if (!c.learn?.length || !c.modules?.length) throw new Error(`Empty content: ${c.id}`);
}
const missing = [...KNOWN_IDS].filter((id) => !seen.has(id));
if (missing.length) throw new Error(`Courses with no authored content: ${missing.join(', ')}`);

const out = [];
out.push('-- MLUE course catalogue content.');
out.push('-- Generated by scripts/build-course-sql.mjs — do not edit by hand.');
out.push('-- Safe to run more than once: nothing is deleted and no non-empty column is overwritten.');
out.push('');
out.push('begin;');
out.push('');

let modules = 0;
let lessons = 0;
let materials = 0;

for (const c of COURSE_CONTENT) {
  out.push(`-- ${'='.repeat(70)}`);
  out.push(`-- ${c.id}`);
  out.push(`-- ${'='.repeat(70)}`);

  out.push(`update courses set
  mentor              = coalesce(nullif(mentor, ''), ${q(c.mentor)}),
  mentor_title        = coalesce(nullif(mentor_title, ''), ${q(c.mentorTitle)}),
  summary             = coalesce(nullif(summary, ''), ${q(c.summary)}),
  what_you_will_learn = case
                          when what_you_will_learn is null or cardinality(what_you_will_learn) = 0
                          then ${arr(c.learn)}
                          else what_you_will_learn
                        end,
  thumbnail_url       = coalesce(nullif(thumbnail_url, ''), ${q(`/course-covers/${c.id}.jpg`)})
where id = ${q(c.id)};`);
  out.push('');

  c.modules.forEach((m, mi) => {
    const mid = `m${mi + 1}`;
    modules += 1;
    out.push(`insert into modules (id, course_id, title, position)
select ${q(mid)}, ${q(c.id)}, ${q(m.title)}, ${mi + 1}
where not exists (select 1 from modules where course_id = ${q(c.id)} and id = ${q(mid)});`);

    m.lessons.forEach((title, li) => {
      const lid = `${mid}-l${li + 1}`;
      lessons += 1;
      out.push(`insert into lessons (id, course_id, module_id, title, duration, position)
select ${q(lid)}, ${q(c.id)}, ${q(mid)}, ${q(title)}, ${q(duration(c.id + lid))}, ${li + 1}
where not exists (select 1 from lessons where course_id = ${q(c.id)} and id = ${q(lid)});`);
    });
    out.push('');
  });

  (c.materials || []).forEach((name, i) => {
    const id = `mat${i + 1}`;
    materials += 1;
    out.push(`insert into materials (id, course_id, name, position)
select ${q(id)}, ${q(c.id)}, ${q(name)}, ${i + 1}
where not exists (select 1 from materials where course_id = ${q(c.id)} and id = ${q(id)});`);
  });
  out.push('');
}

out.push('commit;');
out.push('');
out.push(`-- ${COURSE_CONTENT.length} courses, ${modules} modules, ${lessons} lessons, ${materials} materials.`);

process.stdout.write(out.join('\n'));
process.stderr.write(
  `courses=${COURSE_CONTENT.length} modules=${modules} lessons=${lessons} materials=${materials}\n`
);
